import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { commonEvents, commonProps, elements } from "./dom-elements.mjs";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceOutputRelativePath = "src/dom.generated.mbt";
const testOutputRelativePath = "src/dom_generated_wbtest.mbt";
const checkOnly = process.argv.includes("--check");

function validateData() {
  const names = new Set();
  for (const element of elements) {
    if (names.has(element.name)) {
      throw new Error(`Duplicate generated helper name: ${element.name}`);
    }
    names.add(element.name);
    const params = new Set(["id", "class_name", "class_list", "attrs", "event", "style", "children"]);
    for (const prop of [...commonProps, ...(element.props ?? [])]) {
      if (params.has(prop.param)) {
        throw new Error(`Duplicate parameter ${prop.param} on ${element.name}`);
      }
      params.add(prop.param);
    }
    for (const handler of [...commonEvents, ...(element.events ?? [])]) {
      if (params.has(handler.param)) {
        throw new Error(`Duplicate parameter ${handler.param} on ${element.name}`);
      }
      params.add(handler.param);
    }
  }
}

function moonType(prop) {
  return `${prop.type}?`;
}

function renderEntries(entries, renderEntry) {
  if (entries.length === 0) return "[]";
  return `[\n${entries.map((entry) => `      ${renderEntry(entry)},`).join("\n")}\n    ]`;
}

function renderHelper(element) {
  const props = [...commonProps, ...(element.props ?? [])];
  const events = [...commonEvents, ...(element.events ?? [])];
  const stringProps = props.filter((prop) => prop.type === "String");
  const boolProps = props.filter((prop) => prop.type === "Bool");
  const intProps = props.filter((prop) => prop.type === "Int");
  const floatProps = props.filter((prop) => prop.type === "Float");
  const parameters = [
    "  id? : String,",
    "  class_name? : String,",
    "  class_list? : Array[String] = [],",
    "  attrs? : ElementAttrs,",
    "  event? : ElementEvents,",
    "  style? : RespoStyle = respo_style(),",
  ];
  if (!element.void) parameters.push("  children : Array[VirtualNode],");
  for (const prop of props) parameters.push(`  ${prop.param}? : ${moonType(prop).slice(0, -1)},`);
  for (const handler of events) parameters.push(`  ${handler.param}? : (DOMEvent) -> Unit,`);

  const children = element.void ? "[]" : "children";
  return `///|
/// Generated typed helper for the \`${element.tag}\` ${element.category} element.
pub fn ${element.name}(
${parameters.join("\n")}
) -> VirtualNode {
  generated_dom_element(
    "${element.tag}",
    id,
    class_name,
    class_list,
    attrs,
    event,
    style,
    ${children},
    string_props=${renderEntries(stringProps, (prop) => `("${prop.react}", ${prop.param})`)},
    bool_props=${renderEntries(boolProps, (prop) => `("${prop.react}", ${prop.param})`)},
    int_props=${renderEntries(intProps, (prop) => `("${prop.react}", ${prop.param})`)},
    float_props=${renderEntries(floatProps, (prop) => `("${prop.react}", ${prop.param})`)},
    event_props=${renderEntries(events, (handler) => `(${handler.variant}, ${handler.param})`)},
  )
}`;
}

function renderFile() {
  const categories = [...new Set(elements.map((element) => element.category))];
  return `// Code generated by scripts/generate-dom-helpers.mjs; DO NOT EDIT.
// Source: scripts/dom-elements.mjs
// Helpers: ${elements.length}; categories: ${categories.join(", ")}.

///|
fn generated_dom_element(
  name : String,
  id : String?,
  class_name : String?,
  class_list : Array[String],
  attrs : ElementAttrs?,
  event : ElementEvents?,
  style : RespoStyle,
  children : Array[VirtualNode],
  string_props~ : Array[(String, String?)],
  bool_props~ : Array[(String, Bool?)],
  int_props~ : Array[(String, Int?)],
  float_props~ : Array[(String, Float?)],
  event_props~ : Array[(DOMEventType, ((DOMEvent) -> Unit)?)],
) -> VirtualNode {
  let attrs = attrs.unwrap_or_default()
  let event = event.unwrap_or_default()
  if id is Some(value) {
    attrs.set("id", value)
  }
  if combine_classes(class_name, class_list) is Some(value) {
    attrs.set("className", value)
  }
  for prop in string_props {
    let (prop_name, prop_value) = prop
    if prop_value is Some(value) {
      attrs.set(prop_name, value)
    }
  }
  for prop in bool_props {
    let (prop_name, prop_value) = prop
    if prop_value is Some(value) {
      attrs.set_bool(prop_name, value)
    }
  }
  for prop in int_props {
    let (prop_name, prop_value) = prop
    if prop_value is Some(value) {
      attrs.set_int(prop_name, value)
    }
  }
  for prop in float_props {
    let (prop_name, prop_value) = prop
    if prop_value is Some(value) {
      attrs.set_float(prop_name, value)
    }
  }
  for prop in event_props {
    let (event_type, handler) = prop
    if handler is Some(handler) {
      event.set(event_type, handler)
    }
  }
  Element({ name, attrs, event, style, children })
}

${elements.map(renderHelper).join("\n\n")}
`;
}

function renderTestFile() {
  const cases = elements.map((element) => {
    const call = element.void ? `${element.name}()` : `${element.name}([])`;
    return `    ("${element.tag}", ${call}.to_js_obscure()),`;
  });
  return `// Code generated by scripts/generate-dom-helpers.mjs; DO NOT EDIT.
// Source: scripts/dom-elements.mjs

///|
extern "js" fn install_generated_helper_test_react() -> Unit =
  #| () => {
  #|   globalThis.React = {
  #|     createElement: (tag, props, ...children) => ({ tag, props, children }),
  #|   };
  #| }

///|
extern "js" fn generated_helper_test_tag(node : @dom.JsObscure) -> String =
  #| (node) => node.tag

///|
test "all ${elements.length} generated DOM helpers construct their declared tags" {
  install_generated_helper_test_react()
  let cases = [
${cases.join("\n")}
  ]
  for test_case in cases {
    let (expected, node) = test_case
    assert_eq(generated_helper_test_tag(node), expected)
  }
}
`;
}

function writeAndFormat(relativePath, content) {
  const outputPath = resolve(repositoryRoot, relativePath);
  let original = null;
  try {
    original = readFileSync(outputPath, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  writeFileSync(outputPath, content);
  const formatted = spawnSync("moon", ["fmt", relativePath], {
    cwd: repositoryRoot,
    encoding: "utf8",
  });
  if (formatted.status !== 0) {
    process.stderr.write(formatted.stdout);
    process.stderr.write(formatted.stderr);
    process.exit(formatted.status ?? 1);
  }
  return { original, generated: readFileSync(outputPath, "utf8"), relativePath };
}

validateData();
const outputs = [
  writeAndFormat(sourceOutputRelativePath, renderFile()),
  writeAndFormat(testOutputRelativePath, renderTestFile()),
];
const categories = [...new Set(elements.map((element) => element.category))];
const staleOutputs = outputs.filter(({ original, generated }) => original !== generated);
if (checkOnly && staleOutputs.length > 0) {
  console.error(`${staleOutputs.map(({ relativePath }) => relativePath).join(", ")} is stale; run yarn generate:dom`);
  process.exit(1);
}
console.log(`Generated ${elements.length} helpers across ${categories.length} categories plus their smoke matrix`);
